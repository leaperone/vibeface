#!/usr/bin/env python3
"""Count maintained source at Git revisions without dependencies or build output."""

import json
import os
import re
import subprocess
import sys
from pathlib import Path, PurePosixPath


EXTENSIONS = set("rs go swift kt kts java ts tsx js jsx mjs cjs py sh bash zsh ps1 c cc cpp h hpp m mm html css scss sass less vue svelte proto sql sol dart rb lua pl cmake".split())
EXCLUDED = set("node_modules vendor vendors third_party third-party generated __generated__ dist build target .artifacts .git .worktrees Pods Carthage .next .expo coverage".split())
GENERATED_PATH = re.compile(r"(\.d\.ts$|\.min\.(js|css)$|\.pb\.(go|cc|h)$|\.generated\.|\.g\.(dart|cs)$|routeTree\.gen\.)")
GENERATED_HEADER = re.compile(r"(?im)^\s*(?://|/\*|\*|#|--|<!--)?\s*(?:@generated|Code generated .*DO NOT EDIT|This file (?:is |was )?(?:automatically )?generated|Automatically generated|Generated by (?:protoc|the protocol buffer compiler|UniFFI|uniffi|ts-rs))")


def selected(path):
    parts = PurePosixPath(path)
    return ("trash" not in path.lower() and not EXCLUDED.intersection(parts.parts)
            and parts.suffix.lstrip(".").lower() in EXTENSIONS
            and not GENERATED_PATH.search(path))


def nonblank(data):
    return sum(bool(line.strip()) for line in data.splitlines())


def count(revision):
    if revision == "WORKTREE":
        paths = subprocess.check_output(["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"]).decode().split("\0")
        entries = [(path, None) for path in paths if selected(path) and Path(path).is_file() and not Path(path).is_symlink()]
        objects = None
        identity = "WORKTREE"
    else:
        identity = subprocess.check_output(["git", "rev-parse", "--verify", revision + "^{commit}"], text=True).strip()
        entries = []
        for entry in subprocess.check_output(["git", "ls-tree", "-r", "-z", identity]).split(b"\0"):
            if not entry:
                continue
            metadata, raw_path = entry.split(b"\t", 1)
            mode, kind, oid = metadata.split()
            path = raw_path.decode()
            if kind == b"blob" and mode != b"120000" and selected(path):
                entries.append((path, oid))
        objects = subprocess.check_output(["git", "cat-file", "--batch"], input=b"".join(oid + b"\n" for _, oid in entries))
    offset = 0
    files = []
    for path, oid in entries:
        if objects is None:
            data = Path(path).read_bytes()
        else:
            end = objects.index(b"\n", offset)
            object_id, kind, size = objects[offset:end].split()
            assert object_id == oid and kind == b"blob"
            size = int(size)
            data = objects[end + 1:end + 1 + size]
            assert len(data) == size and objects[end + 1 + size:end + 2 + size] == b"\n"
            offset = end + size + 2
        if b"\0" not in data and not GENERATED_HEADER.search(data[:2000].decode(errors="replace")):
            files.append({"path": path, "nonblank": nonblank(data), "bytes": len(data)})
    assert objects is None or offset == len(objects)
    return {"revision": identity, "nonblank": sum(f["nonblank"] for f in files),
            "bytes": sum(f["bytes"] for f in files), "files": files}


def self_test():
    assert selected("apps/core/src/store/tests.rs")
    assert selected("scripts/source-size.py")
    for path in ["vendor/a.rs", "apps/app/dist/a.js", "x/trash/a.py", "x/a.pb.go", "x/a.d.ts", "x/routeTree.gen.ts", "README.md", "Cargo.lock"]:
        assert not selected(path), path
    assert nonblank(b"// comment\n\nlet a = 1;\n  \n") == 2
    assert GENERATED_HEADER.search("// Code generated by protoc. DO NOT EDIT.")
    assert not GENERATED_HEADER.search("// Manually maintained protocol definitions.")
    print("source-size self-test passed")


if __name__ == "__main__":
    if sys.argv[1:] == ["--self-test"]:
        self_test()
    else:
        root = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
        os.chdir(root)
        snapshots = [count(ref) for ref in sys.argv[1:] or ["HEAD"]]
        result = {"method": "nonblank physical source lines; comments, tests and scripts included", "snapshots": snapshots}
        if len(snapshots) == 2:
            before, after = snapshots
            result.update(removed=before["nonblank"] - after["nonblank"],
                          reduction=(before["nonblank"] - after["nonblank"]) / before["nonblank"])
        print(json.dumps(result, indent=2))
