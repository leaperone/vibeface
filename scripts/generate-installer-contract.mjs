#!/usr/bin/env node
/** Maintainer-only generator for the self-contained installer contract blocks. */
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadRuntimeCorpus, validateRuntimeCorpus } from './runtime-contract.mjs';
import { loadRuntimeDefinitions } from './release-contract.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BASH = path.join(ROOT, 'install.sh');
const POWERSHELL = path.join(ROOT, 'scripts/install.ps1');
const BEGIN_SH = '# BEGIN AUTO-16 GENERATED INSTALLER CONTRACTS';
const END_SH = '# END AUTO-16 GENERATED INSTALLER CONTRACTS';
const BEGIN_PS = '# BEGIN AUTO-16 GENERATED INSTALLER CONTRACTS';
const END_PS = '# END AUTO-16 GENERATED INSTALLER CONTRACTS';
const IDENT = /^[a-z][a-z0-9_-]*$/;
const TARGET = /^[a-z0-9_-]+$/;
const PATH = /^[A-Za-z0-9._/-]+$/;
function fail(message) { throw new Error(`installer contract: ${message}`); }
function checkString(value, re, label) {
  if (typeof value !== 'string' || !value || !re.test(value) || /['"`$\\\n\r;]/.test(value)) fail(`unsafe ${label}`);
  if (value.startsWith('/') || value.includes('\\') || value.split('/').some(part => !part || part === '.' || part === '..')) fail(`unsafe ${label}`);
  return value;
}
function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (value && typeof value === 'object') return Object.fromEntries(Object.keys(value).sort().map(key => [key, canonical(value[key])]));
  return value;
}
function projection(runtime, definitions, web) {
  return canonical({
    schema: runtime.schema,
    wire: runtime.wire,
    contracts: runtime.contracts,
    fields: runtime.build_info.fields,
    types: runtime.build_info.types,
    targets: definitions.targets.map(row => ({ target: row.target, host: row.host, platform: row.platform,
      programs: row.programs, service_suffix: row.service_suffix, roles: { 'node-full': row.roles['node-full'] } })),
    node_full_paths: web,
  });
}
function derive() {
  const runtime = loadRuntimeCorpus();
  validateRuntimeCorpus(runtime);
  const definitions = loadRuntimeDefinitions(runtime);
  if (runtime.schema !== 1 || runtime.wire?.build_info !== 1 || runtime.wire?.files !== 1) fail('unsupported schema or wire version');
  if (!Number.isInteger(runtime.contracts?.data_epoch) || !Number.isInteger(runtime.contracts?.update_protocol) ||
      runtime.contracts.data_epoch < 0 || runtime.contracts.data_epoch > 0xffffffff || runtime.contracts.update_protocol < 0 || runtime.contracts.update_protocol > 0xffffffff) fail('invalid contracts');
  const fields = [...runtime.build_info.fields];
  const expectedFields = ['version','target','source_commit','update_protocol','data_epoch','core_version','core_source_commit','app_version','app_source_commit'];
  assert.deepEqual(fields, expectedFields, 'unsupported BUILD-INFO fields');
  const types = runtime.build_info.types;
  assert.deepEqual(Object.keys(types).sort(), [...expectedFields].sort(), 'invalid BUILD-INFO types');
  assert.equal(types.update_protocol, 'uint32'); assert.equal(types.data_epoch, 'uint32');
  for (const field of expectedFields) if (!IDENT.test(field)) fail(`unsafe field ${field}`);
  const targets = definitions.targets;
  if (targets.length !== 4) fail('unsupported target count');
  const posix = targets.filter(row => row.service_suffix === 'sh');
  if (posix.length !== 3 || new Set(posix.map(row => JSON.stringify(row.roles['node-full']))).size !== 1 ||
      new Set(posix.map(row => JSON.stringify(row.programs))).size !== 1 || posix.some(row => row.programs.some(name => /\.exe$/.test(name)))) fail('divergent POSIX role sets or programs');
  const nodePaths = [...posix[0].roles['node-full']];
  if (nodePaths.shift() !== 'FILES.sha256') fail('node-full checksum entry must be first');
  for (const row of targets) {
    checkString(row.target, TARGET, 'target'); checkString(row.host, TARGET, 'host');
    for (const program of row.programs) checkString(program, /^[A-Za-z0-9._-]+$/, 'program');
    for (const p of row.roles['node-full']) checkString(p, PATH, 'path');
  }
  const source = projection(runtime, definitions, nodePaths);
  const hash = crypto.createHash('sha256').update(JSON.stringify(source)).digest('hex');
  return { runtime, definitions, fields, nodePaths, hash, source };
}
function q(value) { return `'${value}'`; }
function renderSh(model) {
  const { runtime, definitions, fields, nodePaths, hash } = model;
  const posix = definitions.targets.filter(row => row.service_suffix === 'sh');
  const by = name => definitions.targets.find(row => row.target === name);
  const lines = [BEGIN_SH, '# Generated by scripts/generate-installer-contract.mjs; do not edit.', '# Source: scripts/fixtures/release-contract.json + scripts/package-node-web.json', `# Source projection SHA-256: ${hash}`,
    `readonly AUTO16_DATA_EPOCH=${q(String(runtime.contracts.data_epoch))}`,
    `readonly AUTO16_UPDATE_PROTOCOL=${q(String(runtime.contracts.update_protocol))}`,
    `readonly AUTO16_BUILD_FIELDS=${q(fields.join(' '))}`,
    `readonly AUTO16_BUILD_NUMBER_FIELDS=${q(fields.filter(field => runtime.build_info.types[field] === 'uint32').join(' '))}`,
    `readonly AUTO16_BUILD_FIELD_COUNT=${q(String(fields.length))}`,
    `readonly AUTO16_NODE_REQUIRED_PATHS=(${nodePaths.map(q).join(' ')})`,
    `readonly AUTO16_TARGET_DARWIN_ARM64=${q(by('aarch64-apple-darwin').target)}`,
    `readonly AUTO16_TARGET_LINUX_X64=${q(by('x86_64-unknown-linux-gnu').target)}`,
    `readonly AUTO16_TARGET_LINUX_ARM64=${q(by('aarch64-unknown-linux-gnu').target)}`,
    `readonly AUTO16_PROGRAM_CLI=${q(posix[0].programs[0])}`,
    `readonly AUTO16_PROGRAM_CORE=${q(posix[0].programs[1])}`,
    `readonly AUTO16_GENERATOR_HASH=${q(hash)}`, ': "$AUTO16_GENERATOR_HASH"', END_SH];
  return lines.join('\n');
}
function renderPs(model) {
  const { runtime, definitions, fields, nodePaths, hash } = model;
  const row = definitions.targets.find(item => item.service_suffix === 'ps1');
  const lines = [BEGIN_PS, '# Generated by scripts/generate-installer-contract.mjs; do not edit.', '# Source: scripts/fixtures/release-contract.json + scripts/package-node-web.json', `# Source projection SHA-256: ${hash}`,
    `$Auto16DataEpoch = ${runtime.contracts.data_epoch}`,
    `$Auto16UpdateProtocol = ${runtime.contracts.update_protocol}`,
    `$Auto16BuildFields = @(${fields.map(q).join(', ')})`,
    `$Auto16BuildFieldCount = ${fields.length}`,
    `$Auto16NodeRequiredPaths = @(${row.roles['node-full'].filter(p => p !== 'FILES.sha256').map(p => q(p.replaceAll('/', '\\'))).join(', ')})`,
    `$Auto16Target = ${q(row.target)}`, `$Target = $Auto16Target`,
    `$Auto16ProgramCli = ${q(row.programs[0])}`,
    `$Auto16ProgramCore = ${q(row.programs[1])}`,
    `$Auto16GeneratorHash = ${q(hash)}`, END_PS];
  return lines.join('\n');
}
function replaceBlock(file, begin, end, rendered) {
  const text = fs.readFileSync(file, 'utf8');
  const starts = [...text.matchAll(new RegExp(`^${begin.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`, 'gm'))];
  const ends = [...text.matchAll(new RegExp(`^${end.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`, 'gm'))];
  if (starts.length !== 1 || ends.length !== 1 || starts[0].index >= ends[0].index) fail(`malformed generated markers in ${path.relative(ROOT, file)}`);
  const start = starts[0].index; const finish = ends[0].index + end.length;
  return text.slice(0, start) + rendered + text.slice(finish);
}
function main() {
  const mode = process.argv.slice(2); if (mode.length !== 1 || !['--write','--check'].includes(mode[0])) fail('usage: --write or --check');
  const model = derive();
  const sh = replaceBlock(BASH, BEGIN_SH, END_SH, renderSh(model));
  const ps = replaceBlock(POWERSHELL, BEGIN_PS, END_PS, renderPs(model));
  const oldSh = fs.readFileSync(BASH, 'utf8'); const oldPs = fs.readFileSync(POWERSHELL, 'utf8');
  if (mode[0] === '--check') {
    if (sh !== oldSh || ps !== oldPs) { console.error('installer generated blocks are stale'); process.exitCode = 1; return; }
    return;
  }
  fs.writeFileSync(BASH, sh); fs.writeFileSync(POWERSHELL, ps);
}
try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; }
