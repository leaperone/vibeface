#!/usr/bin/env python3
"""Derive Web utilities and native tokens from the pinned Arc foundation."""

import argparse
import json
import math
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
FOUNDATION = ROOT / "packages/uiarc/src/foundation.css"
MOTION = ROOT / "packages/uiarc/src/motion-tokens.ts"
THEME = ROOT / "packages/theme"
BLOCK = re.compile(r'(:root(?:\[[^\]]*\])*)\s*\{([^{}]*)\}')
DECLARATION = re.compile(r'(--[\w-]+)\s*:\s*([^;]+);')
COLORS = (
    "background surface surface-raised surface-muted foreground text-secondary text-muted "
    "border border-subtle border-strong accent accent-strong accent-subtle accent-foreground "
    "control-on control-glyph control-track control-track-hover control-thumb control-thumb-on control-fill "
    "success warning danger info tone-teal tone-sky tone-orchid tone-violet tone-rose tone-amber tone-green"
).split()
STATUS = ("success", "warning", "danger", "info")
HEADER = "/* Generated by scripts/generate-uiarc-theme.py. Edit the pinned Arc source or generator. */\n"


def declarations():
    text = re.sub(r'/\*.*?\*/', '', FOUNDATION.read_text(), flags=re.S)
    light, dark = {}, {}
    for selector, body in BLOCK.findall(text.split('@supports', 1)[0]):
        if selector == ':root':
            light.update(DECLARATION.findall(body))
        elif selector == ':root[data-theme="dark"]':
            dark.update(DECLARATION.findall(body))
    return light, {**light, **dark}


def resolve(value, variables):
    return re.sub(r'var\((--[\w-]+)\)', lambda match: resolve(variables[match[1]], variables), value)


def srgb_to_linear(channel):
    return channel / 12.92 if channel <= .04045 else ((channel + .055) / 1.055) ** 2.4


def linear_to_srgb(channel):
    return 12.92 * channel if channel <= .0031308 else 1.055 * channel ** (1 / 2.4) - .055


def from_lab(lightness, a, b, alpha=1):
    ll = (lightness + .3963377774 * a + .2158037573 * b) ** 3
    mm = (lightness - .1055613458 * a - .0638541728 * b) ** 3
    ss = (lightness - .0894841775 * a - 1.2914855480 * b) ** 3
    return [linear_to_srgb(x) for x in (
        4.0767416621 * ll - 3.3077115913 * mm + .2309699292 * ss,
        -1.2684380046 * ll + 2.6097574011 * mm - .3413193965 * ss,
        -.0041960863 * ll - .7034186147 * mm + 1.7076147010 * ss,
    )] + [alpha]


def to_lab(color):
    red, green, blue = map(srgb_to_linear, color[:3])
    ll, mm, ss = [math.cbrt(x) for x in (
        .4122214708 * red + .5363325363 * green + .0514459929 * blue,
        .2119034982 * red + .6806995451 * green + .1073969566 * blue,
        .0883024619 * red + .2817188376 * green + .6299787005 * blue,
    )]
    return [
        .2104542553 * ll + .7936177850 * mm - .0040720468 * ss,
        1.9779984951 * ll - 2.4285922050 * mm + .4505937099 * ss,
        .0259040371 * ll + .7827717662 * mm - .8086757660 * ss,
    ]


def color(value, variables):
    value = resolve(value, variables).strip()
    if value == "transparent":
        return [0, 0, 0, 0]
    if value.startswith('#'):
        digits = value[1:]
        if len(digits) in (3, 4):
            digits = ''.join(ch * 2 for ch in digits)
        if len(digits) == 6:
            digits += 'ff'
        return [int(digits[i:i + 2], 16) / 255 for i in (0, 2, 4, 6)]
    match = re.fullmatch(r'oklch\(([^)]+)\)', value)
    if match:
        parts = match[1].replace('/', ' ').split()
        lightness = float(parts[0].strip('%')) / (100 if parts[0].endswith('%') else 1)
        chroma, hue = float(parts[1]), math.radians(float(parts[2]))
        alpha = float(parts[3].strip('%')) / (100 if parts[3].endswith('%') else 1) if len(parts) > 3 else 1
        return from_lab(lightness, chroma * math.cos(hue), chroma * math.sin(hue), alpha)
    match = re.fullmatch(r'rgb\(([^)]+)\)', value)
    if match:
        parts = match[1].replace('/', ' ').replace(',', ' ').split()
        return [float(x.strip('%')) / (100 if x.endswith('%') else 255) for x in parts[:3]] + [float(parts[3]) if len(parts) > 3 else 1]
    raise ValueError(f"Unsupported native color expression: {value}")


def hex_color(channels):
    values = [max(0, min(255, round(channel * 255))) for channel in channels]
    return '#' + ''.join(f'{channel:02x}' for channel in (values[:3] if values[3] == 255 else values))


def mix(left, right, amount):
    components = [a * amount + b * (1 - amount) for a, b in zip(to_lab(left), to_lab(right))]
    return from_lab(*components, left[3] * amount + right[3] * (1 - amount))


def pixel(value):
    result = float(value.removesuffix('rem').removesuffix('px')) * (16 if value.endswith('rem') else 1)
    return int(result) if result.is_integer() else result


def tokens(light):
    motion = MOTION.read_text()
    durations = re.search(r'duration:\s*\{([^}]+)\}', motion)[1]
    return {
        "radius": {name: pixel(light['--radius-' + name]) for name in ('control', 'panel', 'surface', 'pill')},
        "space": {name.removeprefix('--space-'): pixel(value) for name, value in light.items() if name.startswith('--space-')},
        "controlHeight": {name: pixel(light['--control-height-' + name]) for name in ('sm', 'md', 'lg')},
        "fontSize": {name.removeprefix('--text-'): pixel(value) for name, value in light.items() if re.fullmatch(r'--text-(?:xs|sm|base|lg|xl|[2-5]xl)', name)},
        "duration": {name: round(float(value) * 1000) for name, value in re.findall(r'(\w+):\s*([\d.]+)', durations)},
        "ease": {name: [float(x) for x in values.split(',')] for name, values in re.findall(r'(enter|exit|standard|inOut):\s*\[([\d., ]+)\]', motion)},
    }


def utility_theme(light, native=False):
    roles = COLORS + [role + suffix for role in STATUS for suffix in ('-subtle', '-border')]
    lines = ["@theme inline {"]
    lines.extend(f"  --color-{name}: var(--{name});" for name in roles)
    # Tailwind adds the utility's own text-/border- prefix. Keep the public
    # utility names equal to the semantic role used by both app compositions.
    for utility, role in {'secondary': 'text-secondary', 'muted': 'text-muted', 'strong': 'border-strong', 'subtle': 'border-subtle'}.items():
        lines.append(f'  --color-{utility}: var(--{role});')
    lines.extend([
        '  --font-sans: var(--font-body);',
        '  --font-display: var(--font-geist, "Geist Variable"), sans-serif;',
        '  --font-mono: var(--font-code);',
        '  --default-transition-duration: var(--duration-fast);',
        '  --default-transition-timing-function: var(--ease-standard);',
        '  --ease-out: var(--ease-standard);',
    ])
    for name, value in light.items():
        if name.startswith('--radius-') or re.fullmatch(r'--text-(?:xs|sm|base|lg|xl|[2-5]xl)', name):
            lines.append(f'  {name}: {pixel(value)}px;' if native else f'  {name}: {value};')
        if re.fullmatch(r'--text-(?:xs|sm|base|lg|xl|[2-5]xl)', name):
            leading = light['--leading-display' if pixel(value) >= 30 else '--leading-body']
            height = f'{pixel(value) * float(leading):.4f}'.rstrip('0').rstrip('.') + 'px' if native else leading
            lines.append(f'  {name}--line-height: {height};')
    if not native:
        lines.extend(['  --shadow-floating: var(--arc-shadow-floating);', '  --shadow-resting: var(--arc-shadow-resting);'])
    return '\n'.join(lines + ['}', ''])


def outputs():
    light, dark = declarations()
    theme_tokens = tokens(light)
    native_colors = {}
    for theme, variables in (("light", light), ("dark", dark)):
        values = {name: color(variables['--' + name], variables) for name in COLORS}
        for role in STATUS:
            values[role + '-subtle'] = mix(values[role], values['surface'], .1)
            values[role + '-border'] = mix(values[role], values['border'], .24)
        native_colors[theme] = {name: hex_color(channels) for name, channels in values.items()}
    common = [':root {',
              '  --font-code: "Geist Mono Variable", ui-monospace, monospace;',
              '  --font-inter: "Inter Variable", "PingFang SC", "Microsoft YaHei", system-ui;',
              '  --font-geist: "Geist Variable", "PingFang SC", "Microsoft YaHei", system-ui;',
              '  --arc-shadow-floating: ' + light['--shadow-floating'] + ';',
              '  --arc-shadow-resting: ' + light['--shadow-resting'] + ';']
    for role in STATUS:
        common.extend([
            f'  --{role}-subtle: color-mix(in oklab, var(--{role}) 10%, var(--surface));',
            f'  --{role}-border: color-mix(in oklab, var(--{role}) 24%, var(--border));',
        ])
    common.extend(['}', ':root[data-theme="dark"] {',
                   '  --arc-shadow-floating: ' + dark['--shadow-floating'] + ';',
                   '  --arc-shadow-resting: ' + dark['--shadow-resting'] + ';', '}', ''])
    web = HEADER + '@import "../uiarc/src/foundation.css";\n\n' + '\n'.join(common) + utility_theme(light)
    native = [HEADER.rstrip(), '@layer theme {', '  :root {']
    for name, value in light.items():
        if name.startswith(('--space-', '--radius-', '--control-height-', '--duration-')):
            native.append(f'    {name}: {value};')
    native.extend(['    --font-body: "Inter";', '    --font-geist: "Geist";', '    --font-code: "Geist Mono";', '    --ease-standard: ' + light['--ease-standard'] + ';'])
    for theme in ('light', 'dark'):
        native.append(f'    @variant {theme} {{')
        native.extend(f'      --{name}: {value};' for name, value in native_colors[theme].items())
        native.append('    }')
    native.extend(['  }', '}', '', utility_theme(light, native=True)])
    ts = '// Generated by scripts/generate-uiarc-theme.py.\n'
    ts += 'export const arcTokens = ' + json.dumps(theme_tokens, indent=2) + ' as const\n\n'
    ts += 'export const arcColors = ' + json.dumps(native_colors, indent=2) + ' as const\n'
    return {THEME / 'theme.css': web, THEME / 'native.css': '\n'.join(native), THEME / 'tokens.ts': ts}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    mismatches = []
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                mismatches.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if mismatches:
        parser.exit(1, 'Stale Arc token files: ' + ', '.join(mismatches) + '\nRun python3 scripts/generate-uiarc-theme.py\n')
    print('Arc Web and native tokens ' + ('verified' if args.check else 'generated') + ' from pinned source')


if __name__ == '__main__':
    main()
