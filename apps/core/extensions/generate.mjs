// Run with --check to verify the exact bytes embedded by Rust.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const here = (path) => new URL(path, import.meta.url);
const read = (path) => readFileSync(here(path), "utf8");
const owner = "// vibeface: `vibeface hooks install` writes this file and `vibeface hooks uninstall` removes it.";
const shared = read("transport.mts").replace("export function runHook(", "function runHook(");
const localImport = 'import { runHook } from "./transport.mts";\n';
const checking = process.argv[2] === "--check";

for (const provider of ["pi", "opencode"]) {
  const name = provider + ".ts";
  const adapter = read(name);
  if (!adapter.startsWith(localImport)) throw new Error("Missing transport import in " + name);
  const result = [owner, "// Generated by apps/core/extensions/generate.mjs.", shared, adapter.slice(localImport.length)].join("\n");
  const destination = "generated/" + name;
  if (checking) {
    if (read(destination) !== result) throw new Error("Regenerate " + destination);
  } else {
    mkdirSync(here("generated/"), { recursive: true });
    writeFileSync(here(destination), result);
  }
}
