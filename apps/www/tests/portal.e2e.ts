import { test } from '@e2e-dev/web'
import { expect } from 'e2e'

test('portal serves docs and searches Chinese content', async ({ app, screen, browser }) => {
  await browser.setViewport({ width: 1280, height: 900 })
  await app.open('/')
  await expect(screen.getByRole('heading', { name: /Your computers\.\s*One conversation\./ })).toBeVisible()
  expect(await browser.evaluate(() => document.documentElement.lang)).toBe('en')

  await screen.getByRole('link', { name: 'Start with one computer', exact: true }).click()
  await expect(screen.getByRole('heading', { name: '快速上手', exact: true })).toBeVisible()
  expect(await browser.evaluate(() => document.documentElement.lang)).toBe('zh-CN')
  await app.screenshot('quick-start')
  await screen.getByRole('link', { name: '首次配置与加入设备', exact: true }).last().click()
  await expect(screen.getByRole('heading', { name: '首次配置与加入设备', exact: true })).toBeVisible()
  await app.screenshot('onboarding')
  await screen.getByRole('link', { name: '日常使用指南', exact: true }).first().click()
  await expect(screen.getByRole('heading', { name: '日常使用指南', exact: true })).toBeVisible()
  await app.screenshot('user-guide')
  await screen.getByRole('link', { name: '安装与管理节点', exact: true }).first().click()
  await expect(screen.getByRole('heading', '安装与管理节点')).toBeVisible()
  await screen.getByRole('button', { name: '打开文档搜索' }).first().click()
  await screen.getByRole('combobox').fill('恢复包')
  await expect(screen.getByRole('option').filter({ hasText: '恢复包' }).first()).toBeVisible()

  await app.open('/')
  await screen.getByRole('link', { name: 'Docs' }).click()
  await expect(screen.getByRole('heading', 'Vibeface 能帮你做什么')).toBeVisible()
  await screen.getByRole('link', { name: '与原生工具及 OpenClaw 的比较' }).click()
  await expect(screen.getByRole('heading', '已有 Agent，为什么还用 Vibeface')).toBeVisible()

  await screen.getByRole('button', { name: '打开文档搜索' }).first().click()
  await screen.getByRole('combobox').fill('事件的发生顺序')
  await screen.getByRole('option').filter({ hasText: '事件的发生顺序' }).first().click()
  await expect(browser).toHaveURL(/\/docs\/history-sync\/?(?:#.*)?$/)
  await expect(screen.getByRole('heading', '换设备时，哪些历史会同步')).toBeVisible()

  await screen.getByRole('button', { name: '打开文档搜索' }).first().click()
  await screen.getByRole('combobox').fill('被盗管理设备')
  await screen.getByRole('option').filter({ hasText: '被盗管理设备' }).first().click()
  await expect(browser).toHaveURL(/\/docs\/privacy-security\/?(?:#.*)?$/)
  await expect(screen.getByRole('heading', '谁能读到内容，权限在哪里生效')).toBeVisible()
  await screen.getByRole('link', { name: 'Bot 与任务执行' }).click()
  await expect(screen.getByRole('heading', 'Bot 如何协调，Agent 在哪里执行')).toBeVisible()

  await app.open('/security')
  await screen.getByRole('button', { name: 'Switch to dark theme' }).click()
  await expect(screen.getByRole('button', { name: 'Switch to light theme' })).toBeVisible()
  await app.open('/')
  await browser.setViewport({ width: 390, height: 844 })
  await expect(screen.getByRole('link', { name: 'Docs' })).toBeVisible()
  await expect(screen.getByRole('link', { name: 'Download' })).toBeVisible()
  expect(await browser.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await browser.setViewport({ width: 320, height: 844 })
  expect(await browser.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  expect(await browser.evaluate(() => {
    const nodes = [...document.querySelectorAll('.visual-node')].map((node) => node.getBoundingClientRect())
    return nodes.some((a, i) => nodes.slice(i + 1).some((b) => a.left < b.right && a.right > b.left && a.top < b.bottom && a.bottom > b.top))
  })).toBe(false)
  expect(await browser.evaluate(() => {
    const diagram = document.querySelector('.hero-visual')!.getBoundingClientRect()
    return [...document.querySelectorAll('.visual-node')].every((node) => {
      const rect = node.getBoundingClientRect()
      return rect.left >= diagram.left && rect.right <= diagram.right && rect.top >= diagram.top && rect.bottom <= diagram.bottom
    })
  })).toBe(true)

  await app.open('/404.html')
  await expect(screen.getByRole('heading', '这条路径没有内容。')).toBeVisible()
})


test('portal and documentation share a persistent readable theme', async ({ app, screen, browser }) => {
  await browser.setViewport({ width: 1280, height: 900 })
  await app.open('/')
  await screen.getByRole('button', 'Switch to dark theme').click()
  await expect(screen.getByRole('button', 'Switch to light theme')).toBeVisible()
  const dark = await browser.evaluate(() => getComputedStyle(document.querySelector('.landing')!).backgroundColor)
  await app.screenshot('home-dark')
  await screen.getByRole('button', 'Switch to light theme').click()
  await expect(screen.getByRole('button', 'Switch to dark theme')).toBeVisible()
  const light = await browser.evaluate(() => getComputedStyle(document.querySelector('.landing')!).backgroundColor)
  expect(light).not.toBe(dark)
  await app.screenshot('home-light')
  await browser.reload()
  await expect(screen.getByRole('button', 'Switch to dark theme')).toBeVisible()
  expect(await browser.evaluate(() => getComputedStyle(document.querySelector('.landing')!).backgroundColor)).toBe(light)
  for (const path of ['/download/', '/community/', '/security/']) {
    await app.open(path)
    await expect(screen.getByRole('button', 'Switch to dark theme')).toBeVisible()
    expect(await browser.evaluate(() => getComputedStyle(document.querySelector('.site')!).backgroundColor)).toBe(light)
  }
  await app.open('/docs/')
  await expect(screen.getByRole('heading', 'Vibeface 能帮你做什么')).toBeVisible()
  expect(await browser.evaluate(() => getComputedStyle(document.querySelector('.site-docs')!).backgroundColor)).toBe(light)
  await app.screenshot('docs-light')
  await screen.getByRole('button', '切换主题').click()
  expect(await browser.evaluate(() => getComputedStyle(document.querySelector('.site-docs')!).backgroundColor)).toBe(dark)
  await browser.reload()
  await expect(screen.getByRole('heading', 'Vibeface 能帮你做什么')).toBeVisible()
  expect(await browser.evaluate(() => getComputedStyle(document.querySelector('.site-docs')!).backgroundColor)).toBe(dark)
  await app.screenshot('docs-dark')
  await screen.getByRole('button', '打开文档搜索').first().click()
  await screen.getByRole('combobox').fill('恢复包')
  await expect(screen.getByRole('option').filter({ hasText: '恢复包' }).first()).toBeVisible()
  await app.screenshot('search-dark')
  await app.open('/docs/quick-start/')
  await expect(screen.getByRole('heading', { name: '快速上手', exact: true })).toBeVisible()
  await browser.setViewport({ width: 390, height: 844 })
  await app.screenshot('docs-mobile-dark')
  expect(await browser.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await app.open('/404.html')
  await expect(screen.getByRole('heading', '这条路径没有内容。')).toBeVisible()
  expect(await browser.evaluate(() => getComputedStyle(document.body).backgroundColor)).toBe(dark)
  await app.open('/')
  await screen.getByRole('button', 'Switch to light theme').click()
  expect(await browser.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await app.screenshot('home-mobile-light')
  await app.open('/404.html')
  expect(await browser.evaluate(() => getComputedStyle(document.body).backgroundColor)).toBe(light)
})
