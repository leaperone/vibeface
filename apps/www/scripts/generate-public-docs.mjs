import { readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const portalRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const docsRoot = resolve(portalRoot, '../../packages/docs')

/** Registry group and page order is navigation order. Files and routes share a basename. */
export function readPublicDocGroups(registry = JSON.parse(readFileSync(resolve(portalRoot, 'public-docs.json'), 'utf8'))) {
  if (!registry || !Array.isArray(registry.groups) || registry.groups.length === 0) throw new Error('public-docs.json must contain non-empty groups')
  const seen = new Set()
  const titles = new Set()
  return registry.groups.map((group) => {
    if (!group || typeof group.title !== 'string' || !group.title.trim() || !Array.isArray(group.pages) || group.pages.length === 0) throw new Error('Each public document group needs a title and non-empty pages')
    if (titles.has(group.title)) throw new Error(`Duplicate public document group: ${group.title}`)
    titles.add(group.title)
    return { title: group.title, pages: group.pages.map((slug) => {
      if (typeof slug !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) throw new Error(`Invalid public document slug: ${JSON.stringify(slug)}`)
      if (seen.has(slug)) throw new Error(`Duplicate public document slug: ${slug}`)
      seen.add(slug)
      const file = `${slug}.md`
      if (!statSync(resolve(docsRoot, file)).isFile()) throw new Error(`Public document is not a file: ${file}`)
      return { file, slug }
    }) }
  })
}

export function readPublicDocs() {
  return readPublicDocGroups().flatMap(({ pages }) => pages)
}

function generate(check) {
  const groups = readPublicDocGroups()
  const docs = groups.flatMap(({ pages }) => pages)
  const header = '// Generated by scripts/generate-public-docs.mjs from public-docs.json. Do not edit.\n'
  const outputs = new Map([
    [resolve(portalRoot, 'public/sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url><loc>https://www.vibeface.dev/</loc></url>
  <url><loc>https://www.vibeface.dev/download</loc></url>
  <url><loc>https://www.vibeface.dev/community</loc></url>
  <url><loc>https://www.vibeface.dev/security</loc></url>
${docs.map(({ slug }) => `  <url><loc>https://www.vibeface.dev/docs/${slug}</loc></url>`).join('\n')}
</urlset>
`],
    [resolve(docsRoot, 'meta.json'), `${JSON.stringify({ pages: docs.map(({ slug }) => slug) }, null, 2)}\n`],
    [resolve(portalRoot, 'src/lib/public-docs.ts'), `${header}export const PUBLIC_DOC_GROUPS = [
${groups.map(({ title, pages }) => `  { title: ${JSON.stringify(title)}, pages: ${JSON.stringify(pages.map(({ slug }) => slug))} },`).join('\n')}
] as const

export const PUBLIC_DOCS = PUBLIC_DOC_GROUPS.flatMap(({ pages }) =>
  pages.map(slug => ({ file: \`\${slug}.md\`, slug })),
)
`],
    [resolve(portalRoot, 'src/lib/source.ts'), `${header}import { loader } from 'fumadocs-core/source'
import { defineDocs } from 'fumadocs-mdx/macro'

export const docs = defineDocs({
  dir: '../../packages/docs',
  docs: {
    async: true,
    files: [
${docs.map(({ file }) => `      '${file}',`).join('\n')}
    ],
    postprocess: { includeProcessedMarkdown: true },
  },
  meta: { files: ['meta.json'] },
})

export const source = loader({
  source: docs.toFumadocsSource(),
  baseUrl: '/docs',
})
`],
  ])
  for (const [path, content] of outputs) {
    if (check) {
      if (readFileSync(path, 'utf8') !== content) throw new Error(`Stale generated public docs: ${path}. Run pnpm --filter vibeface-www generate:docs`)
    } else {
      writeFileSync(path, content)
    }
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2)
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) throw new Error('Usage: generate-public-docs.mjs [--check]')
  generate(args[0] === '--check')
}
