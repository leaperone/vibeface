test('verifySignedCatalog validates real signature', () => {
  const { defaults, secure, signCatalog } = createTestIssuer()
  const now = 1_700_000_000_000
  const payloadObj = {
    version: 1,
    issuer: defaults.issuer,
    issued_at_ms: now - 10_000,
    expires_at_ms: now + 3600_000,
    entries: [{ gateway_url: 'https://gw.test/', relay_url: 'https://relay.test/' }],
  }
  const payload = JSON.stringify(payloadObj)
  const wire = { payload, signature: signCatalog(payload) }
  const v = verifySignedCatalog(wire, secure, defaults, now, httpsOpts)
  assert.equal(v.entries.length, 1)
  assert.throws(() => verifySignedCatalog({ payload, signature: `${'00'.repeat(64)}f` }, secure, defaults, now, httpsOpts), /format invalid/)
})

