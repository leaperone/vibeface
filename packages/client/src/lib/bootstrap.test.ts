test('fetchVerifiedCatalog rejects redirect and accepts ok body', async (t) => {
  const { defaults, secure, signCatalog } = createTestIssuer()
  const now = 1_700_000_000_000
  const payloadObj = {
    version: 1,
    issuer: defaults.issuer,
    issued_at_ms: now - 10_000,
    expires_at_ms: now + 3600_000,
    entries: [{ gateway_url: 'https://gw.test/', relay_url: 'https://relay.test/' }],
  }
  const payload = JSON.stringify(payloadObj)
  const body = JSON.stringify({ payload, signature: signCatalog(payload) })
  const prev = globalThis.fetch
  t.after(() => {
    globalThis.fetch = prev
  })
  globalThis.fetch = (async (url: string | URL, init?: RequestInit) => {
    const u = String(url)
    if (u.includes('/redirect')) return new Response(null, { status: 302, headers: { Location: 'https://evil.test/' } })
    assert.match(u, /\/catalog$/)
    assert.equal(init?.redirect, 'manual')
    return new Response(body, { status: 200, headers: { 'Content-Type': 'application/json' } })
  }) as typeof fetch
  const customMode: PublicBootstrapMode = { kind: 'custom', issuer: defaults.issuer, https_base: 'https://fixture.example/redirect' }
  await assert.rejects(
    () => fetchVerifiedCatalog({ secure, defaults, mode: customMode, nowMs: now, storage: null }),
    /redirect/,
  )
  const goodMode: PublicBootstrapMode = { kind: 'custom', issuer: defaults.issuer, https_base: 'https://fixture.example/good' }
  const got = await fetchVerifiedCatalog({ secure, defaults, mode: goodMode, nowMs: now, storage: null })
  assert.equal(got.entries[0].gateway_url, 'https://gw.test')
})

test('readCachedCatalog re-verifies stored envelope and invokes verifier', () => {
  const { defaults, secure, signCatalog } = createTestIssuer()
  const now = 1_700_000_000_000
  const payloadObj = {
    version: 1,
    issuer: defaults.issuer,
    issued_at_ms: now - 10_000,
    expires_at_ms: now + 3600_000,
    entries: [{ gateway_url: 'https://gw.cache/', relay_url: 'https://relay.cache/' }],
  }
  const payload = JSON.stringify(payloadObj)
  const signature = signCatalog(payload)
  const storage: Record<string, string> = {}
  const mem = {
    getItem(k: string) {
      return storage[k] ?? null
    },
    setItem(k: string, v: string) {
      storage[k] = v
    },
  }
  mem.setItem(
    'vibeface.bootstrap-catalog-cache-v1',
    JSON.stringify({
      v: 2,
      source_key: `${defaults.issuer}:${defaults.https_base}`,
      issuer: defaults.issuer,
      https_base: defaults.https_base,
      fetched_at_ms: now,
      payload,
      signature,
    }),
  )
  let verifyCalls = 0
  const counting: Pick<SecureApi, 'verify'> = {
    verify(...args) {
      verifyCalls += 1
      secure.verify(...args)
    },
  }
  const mode: PublicBootstrapMode = { kind: 'default' }
  const got = readCachedCatalog(mem, mode, counting, now, defaults)
  assert.ok(got)
  assert.equal(verifyCalls, 1)
})

test('malformed custom storage fails closed without official catalogue fetch', async (t) => {
  const { defaults, secure, signCatalog } = createTestIssuer()
  const now = 1_700_000_000_000
  const payloadObj = {
    version: 1,
    issuer: defaults.issuer,
    issued_at_ms: now - 10_000,
    expires_at_ms: now + 3600_000,
    entries: [{ gateway_url: 'https://only.official/', relay_url: 'https://r.official/' }],
  }
  const payload = JSON.stringify(payloadObj)
  const body = JSON.stringify({ payload, signature: signCatalog(payload) })
  const storage: Record<string, string> = {
    'vibeface.bootstrap-public-mode': 'custom',
    'vibeface.bootstrap-public-custom-base': 'not-a-url',
    'vibeface.bootstrap-public-custom-issuer': defaults.issuer,
  }
  const mem = { getItem: (k: string) => storage[k] ?? null, setItem: () => {} }
  const prev = globalThis.fetch
  t.after(() => {
    globalThis.fetch = prev
  })
  let fetchCalls = 0
  globalThis.fetch = (async () => {
    fetchCalls += 1
    return new Response(body, { status: 200 })
  }) as typeof fetch
  const mode = getPublicBootstrapMode(mem)
  assert.equal(mode.kind, 'off')
  await assert.rejects(() => fetchVerifiedCatalog({ secure, defaults, mode, nowMs: now, storage: mem }), /disabled/)
  assert.equal(fetchCalls, 0)
})

test('candidates append catalogue gateways for allowed targets after stored web entrances', () => {
  const target = 'b'.repeat(64)
  const list: Entrance[] = [
    { device_id: target, seq: 1, gateway_url: 'https://old.test', public: true, direct: [], last_ok_ms: 0 },
  ]
  const current: ConnectionEntry = { kind: 'gateway', address: 'https://old.test', device_id: target }
  const catalog: VerifiedCatalog = {
    defaults: {
      issuer: 'c'.repeat(64),
      udp_host: 'd.test',
      udp_port: 1,
      https_base: 'https://x',
    },
    issuer: 'c'.repeat(64),
    issued_at_ms: 0,
    expires_at_ms: 9e15,
    entries: [{ gateway_url: 'https://pub.test', relay_url: 'https://r.test' }],
    payloadUtf8: encoder.encode('{}'),
  }
  const order = candidates(list, current, undefined, { catalog, allowedDeviceIds: new Set([target]) }).map(entryAddress)
  assert.deepEqual(order, ['https://old.test', 'https://pub.test'])
  assert.deepEqual(catalogConnectionEntries(catalog, new Set([target])), [
    { kind: 'gateway', address: 'https://pub.test', device_id: target } satisfies ConnectionEntry,
  ])
})
