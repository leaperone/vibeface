const encoder = new TextEncoder()

function signingMessage(domain: string, payload: Uint8Array): Buffer {
  const digest = createHash('sha256').update(payload).digest()
  return Buffer.from(`vibeface:message:v1:${domain}:${digest.toString('hex')}`, 'utf8')
}

function publicKeyFromDeviceIdHex(deviceIdHex: string): KeyObject {
  const pub = Buffer.from(deviceIdHex, 'hex')
  const spki = Buffer.concat([Buffer.from('302a300506032b6570032100', 'hex'), pub])
  return createPublicKey({ key: spki, format: 'der', type: 'spki' })
}

function rawPublicHex(publicKey: KeyObject): string {
  const der = publicKey.export({ type: 'spki', format: 'der' }) as Buffer
  return der.subarray(-32).toString('hex')
}

function verifyWithNode(deviceId: string, domain: string, payload: Uint8Array, signature: string): void {
  const message = signingMessage(domain, new Uint8Array(payload.buffer, payload.byteOffset, payload.byteLength))
  const key = publicKeyFromDeviceIdHex(deviceId)
  if (!verify(null, message, key, Buffer.from(signature, 'hex'))) throw new Error('invalid device signature')
}

function createTestIssuer(): {
  defaults: PublicBootstrapDefaults
  secure: Pick<SecureApi, 'verify'>
  signCatalog(payload: string): string
} {
  const { publicKey, privateKey } = generateKeyPairSync('ed25519')
  const issuer = rawPublicHex(publicKey)
  const defaults: PublicBootstrapDefaults = {
    issuer,
    udp_host: 'discovery.example.test',
    udp_port: 4792,
    https_base: 'https://fixture.example/bootstrap',
  }
  const secure: Pick<SecureApi, 'verify'> = { verify: verifyWithNode }
  function signCatalog(payload: string): string {
    const message = signingMessage('bootstrap-catalog', new Uint8Array(Buffer.from(payload, 'utf8')))
    return (sign(null, message, privateKey) as Buffer).toString('hex')
  }
  return { defaults, secure, signCatalog }
}

const httpsOpts = { allowLoopbackInEntries: false } as const

test('catalogue vector generated by WebAssembly verifies in the shared client', () => {
  const fixture: unknown = JSON.parse(readFileSync(new URL('../../../../tests/fixtures/bootstrap-catalog.json', import.meta.url), 'utf8'))
  assert(fixture !== null && typeof fixture === 'object' && !Array.isArray(fixture))
  assert('issuer' in fixture && typeof fixture.issuer === 'string')
  assert('now_ms' in fixture && typeof fixture.now_ms === 'number')
  assert('catalog' in fixture)
  const defaults = { ...createTestIssuer().defaults, issuer: fixture.issuer }
  const result = verifySignedCatalog(fixture.catalog, { verify: verifyWithNode }, defaults, fixture.now_ms, httpsOpts)
  assert.deepEqual(result.entries, [{ gateway_url: 'https://gateway.fixture.test', relay_url: 'https://relay.fixture.test' }])
  assert.equal(result.issuer, fixture.issuer)
})

test('an unknown stored mode disables public bootstrap without contacting the default service', async () => {
  const values = new Map([['vibeface.bootstrap-public-mode', 'unknown-mode']])
  const storage = { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { values.set(key, value) } }
  const mode = getPublicBootstrapMode(storage)
  assert.deepEqual(mode, { kind: 'off' })
  const { secure, defaults } = createTestIssuer()
  const previousFetch = globalThis.fetch
  let calls = 0
  globalThis.fetch = async () => { calls += 1; throw new Error('must not contact a public service') }
  try {
    await assert.rejects(fetchVerifiedCatalog({ mode, storage, secure, defaults }), /disabled/)
    assert.equal(calls, 0)
  } finally { globalThis.fetch = previousFetch }
})

