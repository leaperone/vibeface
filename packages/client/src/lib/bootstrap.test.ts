test('catalogues reject unknown protocol fields and overlong origins', () => {
  const issuer = 'a'.repeat(64)
  const now = 1_700_000_000_000
  const payload = { version: 1, issuer, issued_at_ms: now - 1000, expires_at_ms: now + 60_000,
    entries: [{ gateway_url: 'https://gateway.example/', relay_url: 'https://relay.example/' }] }
  assert.throws(() => parseVerifiedCatalogPayload(JSON.stringify({ ...payload, unrecognized: true }), issuer, now, httpsOpts), /unknown fields/)
  const host = ['a'.repeat(63), 'b'.repeat(63), 'c'.repeat(63), 'd'.repeat(61)].join('.')
  assert.throws(() => parseVerifiedCatalogPayload(JSON.stringify({ ...payload,
    entries: [{ gateway_url: `https://${host}`, relay_url: 'https://relay.example/' }] }), issuer, now, httpsOpts), /too long/)
})

