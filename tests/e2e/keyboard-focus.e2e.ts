import { expect, secrets } from 'e2e'
import { test } from './fixtures'

test('returns keyboard focus to task and device openers while retaining the task draft', { timeout: 180000 }, async ({ app, node, screen, browser }) => {
  await browser.setViewport({ width: 390, height: 844 })
  await app.open(node.entry)
  await screen.getByRole('button', '新建我的网络').click()
  await screen.getByLabel('这个节点叫什么？').fill('键盘验收工作站')
  await screen.getByRole('button', '下一步').click()
  await screen.getByLabel(/^恢复密码/).fill(secrets.get('recoveryPassword'))
  await screen.getByRole('button', '下一步').click()
  await browser.waitForDownload(() => screen.getByRole('button', '下载恢复文件').click())
  await screen.getByRole('checkbox', '已把文件和密码分开保存').check()
  await screen.getByRole('button', '完成创建').click()
  await screen.getByRole('button', '稍后设置').click()
  await screen.getByLabel('名称', { exact: true }).fill('键盘验收助手')
  await screen.getByRole('button', '完成', { exact: true }).click()
  await expect(browser).toHaveURL(/\/b\/[^/?#]+$/)

  const taskHistory = screen.getByRole('button', '执行记录', { exact: true })
  await taskHistory.focus()
  await taskHistory.press('Enter')
  await expect(screen.getByRole('dialog', '执行记录')).toBeVisible()
  await expect(screen.getByRole('link', '查看任务对话', { exact: true })).toBeVisible()
  await browser.keyboard.press('Escape')
  await expect(screen.getByRole('dialog')).toHaveCount(0)
  await expect(taskHistory).toBeFocused()

  await browser.goto('/tasks')
  const menu = screen.getByRole('button', '菜单', { exact: true })
  await menu.focus()
  await menu.press('Enter')
  await expect(screen.getByRole('dialog', '导航和会话')).toBeVisible()
  await browser.keyboard.press('Escape')
  await expect(screen.getByRole('dialog')).toHaveCount(0)
  await expect(menu).toBeFocused()
  const newTask = screen.getByRole('button', '新任务', { exact: true })
  await expect(newTask).toBeEnabled()
  await newTask.focus()
  await expect(newTask).toBeFocused()
  await newTask.press('Enter')
  await screen.getByRole('button', '创建并发送', { exact: true }).click()
  await expect(screen.getByLabel('任务名称', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(screen.getByLabel('任务名称', { exact: true })).toBeFocused()
  await screen.getByLabel('任务名称', { exact: true }).fill('关闭后保留的任务草稿')
  await expect(screen.getByLabel('任务名称', { exact: true })).not.toHaveAttribute('aria-invalid', 'true')
  await screen.getByRole('button', '创建并发送', { exact: true }).click()
  await expect(screen.getByLabel('交代内容', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(screen.getByLabel('交代内容', { exact: true })).toBeFocused()
  await app.screenshot('quality-task-field-validation')
  await screen.getByLabel('交代内容', { exact: true }).fill('继续编辑时保留这段交代。')
  await expect(screen.getByLabel('交代内容', { exact: true })).not.toHaveAttribute('aria-invalid', 'true')
  await browser.keyboard.press('Escape')
  await expect(screen.getByRole('dialog')).toHaveCount(0)
  await expect(newTask).toBeFocused()
  await newTask.press('Enter')
  await expect(screen.getByLabel('任务名称', { exact: true })).toHaveValue('关闭后保留的任务草稿')
  await expect(screen.getByLabel('交代内容', { exact: true })).toHaveValue('继续编辑时保留这段交代。')
  await screen.getByRole('button', 'Close drawer', { exact: true }).click()
  await expect(screen.getByRole('dialog')).toHaveCount(0)
  await expect(newTask).toBeFocused()

  await browser.goto('/devices')
  const addDevice = screen.getByRole('button', '添加设备', { exact: true })
  await expect(addDevice).toBeEnabled()
  await addDevice.focus()
  await expect(addDevice).toBeFocused()
  await addDevice.press('Enter')
  await expect(screen.getByRole('dialog')).toBeVisible()
  await browser.keyboard.press('Escape')
  await expect(screen.getByRole('dialog')).toHaveCount(0)
  await expect(addDevice).toBeFocused()
  await addDevice.press('Enter')
  await screen.getByRole('button', 'Close drawer', { exact: true }).click()
  await expect(screen.getByRole('dialog')).toHaveCount(0)
  await expect(addDevice).toBeFocused()

  await browser.goto('/settings')
  const disconnect = screen.getByRole('button', '断开这个浏览器', { exact: true })
  await disconnect.focus()
  await disconnect.press('Enter')
  await expect(screen.getByRole('dialog')).toBeVisible()
  await browser.keyboard.press('Escape')
  await expect(screen.getByRole('dialog')).toHaveCount(0)
  await expect(disconnect).toBeFocused()
  await disconnect.press('Enter')
  await screen.getByRole('button', /^(取消|知道了)$/).click()
  await expect(screen.getByRole('dialog')).toHaveCount(0)
  await expect(disconnect).toBeFocused()

  await browser.goto('/channels')
  const channelOpeners = screen.getByRole('button', '新频道', { exact: true })
  await expect(channelOpeners).toHaveCount(2)
  for (const channelOpener of await channelOpeners.all()) {
    await expect(channelOpener).toBeEnabled()
    await channelOpener.focus()
    await channelOpener.press('Enter')
    await expect(screen.getByRole('dialog', '新频道')).toBeVisible()
    await screen.getByRole('button', '创建频道', { exact: true }).click()
    await expect(screen.getByLabel('频道名称', { exact: true })).toHaveAttribute('aria-invalid', 'true')
    await expect(screen.getByLabel('频道名称', { exact: true })).toBeFocused()
    await expect(screen.getByRole('alert').filter({ hasText: '还没填频道名称' })).toBeVisible()
    await browser.keyboard.press('Escape')
    await expect(screen.getByRole('dialog')).toHaveCount(0)
    await expect(channelOpener).toBeFocused()
  }

  await browser.goto('/')
  await screen.getByRole('button', '新 Bot', { exact: true, visible: true }).click()
  await screen.getByRole('button', '创建', { exact: true }).click()
  const name = screen.getByLabel('名称', { exact: true })
  await expect(name).toHaveAttribute('aria-invalid', 'true')
  await expect(name).toBeFocused()
  await expect(screen.getByRole('alert').filter({ hasText: '还没填名称' })).toBeVisible()
  await app.screenshot('quality-bot-name-validation')
  await name.fill('继续保留的名称')
  await expect(name).not.toHaveAttribute('aria-invalid', 'true')
  await screen.getByLabel('它负责什么', { exact: true }).fill('配置文件夹后继续编辑这段职责。')
  await screen.getByRole('link', '去设置', { exact: true }).click()
  await expect(browser).toHaveURL(/\/devices\/[^/?#]+$/)
  await browser.back()
  await expect(browser).toHaveURL(/\/$/)
  await screen.getByRole('button', '新 Bot', { exact: true, visible: true }).click()
  await expect(name).toHaveValue('继续保留的名称')
  await expect(screen.getByLabel('它负责什么', { exact: true })).toHaveValue('配置文件夹后继续编辑这段职责。')
  await app.screenshot('quality-bot-draft-return')
  await screen.getByRole('button', '取消', { exact: true }).click()
  await expect(screen.getByRole('dialog')).toHaveCount(0)
  await screen.getByRole('button', '新 Bot', { exact: true, visible: true }).click()
  await expect(name).toHaveValue('')
  await expect(screen.getByLabel('它负责什么', { exact: true })).toHaveValue('')
  await browser.keyboard.press('Escape')
})
