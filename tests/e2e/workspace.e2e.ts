import assert from 'node:assert/strict';
import { stat } from 'node:fs/promises';
import { expect, secrets } from 'e2e';
import { workspaceTest as test } from './fixtures';

test('keeps personal Tasks, deferred inputs and directed Channel results in their own scopes', { tags: ['workspace'], timeout: 300000 }, async ({ app, workspace, screen, browser }) => {
  await browser.setViewport({ width: 1440, height: 1000 });
  await app.open(workspace.source.url);
  await screen.getByRole('button', '新建我的网络').click();
  await screen.getByLabel('这个节点叫什么？').fill('Workspace E2E Node');
  await screen.getByRole('button', '下一步').click();
  await expect(screen.getByRole('heading', '设置恢复密码')).toBeVisible();
  await screen.getByLabel(/^恢复密码/).fill(secrets.get('recoveryPassword'));
  await screen.getByRole('button', '下一步').click();
  await expect(screen.getByRole('heading', '保存恢复文件')).toBeVisible();
  const recovery = await browser.waitForDownload(() => screen.getByRole('button', '下载恢复文件').click());
  expect((await stat(recovery.absolutePath)).size).toBeGreaterThan(0);
  await screen.getByRole('checkbox', '已把文件和密码分开保存').check();
  await screen.getByRole('button', '完成创建').click();
  await expect(screen.getByRole('heading', '让这台电脑运行 Bot')).toBeVisible();
  await screen.getByRole('button', '稍后设置').click();
  await screen.getByRole('button', '跳过', { exact: true }).click();

  const createBot = async (name: string) => {
    await screen.getByRole('button', '新 Bot', { visible: true }).first().click();
    const dialog = screen.getByRole('dialog');
    await expect(dialog.getByRole('heading', '新 Bot')).toBeVisible();
    await dialog.getByLabel('名称', { exact: true }).fill(name);
    await dialog.getByRole('button', '创建', { exact: true }).click();
    await expect(browser).toHaveURL(/\/b\/[^/?#]+$/);
    await expect(screen.getByRole('region', '对话').getByRole('heading', name)).toBeVisible();
    return browser.url();
  };
  const invocation = async (label: string) => {
    await expect.poll(async () => (await workspace.inspect()).invocations.filter(row => row.label === label).length, { timeout: 30000 }).toBe(1);
    const row = (await workspace.inspect()).invocations.find(item => item.label === label);
    assert(row, 'The controlled provider recorded this exact input');
    return row;
  };
  const turn = async (threadId: string) => {
    await expect.poll(async () => (await workspace.inspect()).starts.filter(row => row.thread_id === threadId).length, { timeout: 30000 }).toBe(1);
    const row = (await workspace.inspect()).starts.find(item => item.thread_id === threadId);
    assert(row, 'The controlled provider started this scope once');
    return row.turn_id;
  };
  const directive = (label: string, gate: string) => JSON.stringify({ phase1: true, label, gate });
  const createTask = async (title: string, request: string) => {
    await browser.goto('/tasks');
    await screen.getByRole('button', '新任务', { exact: true, visible: true }).first().click();
    const dialog = screen.getByRole('dialog');
    await dialog.getByRole('combobox', '任务 Bot').selectOption({ label: 'Workspace Builder' });
    await dialog.getByLabel('任务名称', { exact: true }).fill(title);
    await dialog.getByLabel('交代内容', { exact: true }).fill(request);
    await dialog.getByRole('button', '创建并发送').click();
    await expect(browser).toHaveURL(/\/tasks\/[^/?#]+$/);
    await expect(screen.getByRole('heading', title, { level: 2 })).toBeVisible();
    return browser.url();
  };

  const builderUrl = await createBot('Workspace Builder');
  await browser.reload();
  await expect(screen.getByRole('region', '对话').getByRole('heading', 'Workspace Builder')).toBeVisible();
  const mainText = directive('workspace-main-only', workspace.gates.main);
  await screen.getByRole('textbox', '给 Bot 发消息').fill(mainText);
  await screen.getByRole('textbox', '给 Bot 发消息').press('Enter');
  const main = await invocation('workspace-main-only');
  const mainTurn = await turn(main.thread_id);
  await createBot('Workspace Reviewer');

  const taskAText = directive('workspace-task-a-only', workspace.gates.taskA);
  const taskAUrl = await createTask('检查官网导航', taskAText);
  const taskA = await invocation('workspace-task-a-only');
  const taskATurn = await turn(taskA.thread_id);
  expect(taskA.conversation_id).toBe(main.conversation_id);
  expect(taskA.thread_id).not.toBe(main.thread_id);
  expect(taskA.messages.some(message => message.includes('workspace-main-only'))).toBe(false);
  const taskChat = screen.getByRole('region', '任务对话');
  const taskAComposer = taskChat.getByRole('textbox', '发给 Workspace Builder · 检查官网导航');
  await expect(taskChat).toContainText('workspace-task-a-only');
  await expect(taskChat.getByRole('button', '补充当前工作')).toBeVisible({ timeout: 20000 });
  const supplements = ['补充一：保留首页入口', '补充二：支持键盘导航', '补充三：检查手机菜单'];
  for (const supplement of supplements) {
    await taskAComposer.fill(supplement);
    await taskAComposer.press('Enter');
    await expect(taskAComposer).toHaveValue('');
    await expect(taskAComposer).toBeFocused();
    await expect(browser).toHaveURL(taskAUrl);
  }
  await expect.poll(async () => (await workspace.inspect()).steers.filter(row => row.thread_id === taskA.thread_id).length, { timeout: 30000 }).toBe(3);
  const accepted = await workspace.inspect();
  const taskAInputs = accepted.steers.filter(row => row.thread_id === taskA.thread_id);
  expect(taskAInputs.map(row => supplements.find(value => row.text.includes(value)))).toEqual(supplements);
  expect(new Set(taskAInputs.map(row => row.message_id)).size).toBe(3);
  expect(taskAInputs.map(row => row.turn_id)).toEqual([taskATurn, taskATurn, taskATurn]);
  expect(accepted.starts.filter(row => row.thread_id === taskA.thread_id)).toHaveLength(1);
  expect(accepted.turns.find(row => row.turn_id === taskATurn)?.state).toBe('inProgress');
  expect(accepted.interrupts).toEqual([]);

  await screen.getByRole('button', '上下文和历史').click();
  const context = screen.getByRole('region', '实际上下文来源与补充回执');
  await expect(context.getByRole('heading', '本轮上下文引用')).toBeVisible();
  await context.getByText('查看来源引用', { exact: true }).click();
  await expect(context.getByRole('listitem').filter({ hasText: /^本轮交代 · / })).toHaveCount(1);
  await expect(context.getByText(/^因预算省略 · 消息 \d+ 条 · 附件 \d+ 个 · 记忆 \d+ 条$/)).toBeVisible();
  await expect(context.getByText(/^第 [123] 条补充 · (执行服务已接受输入|已确认回合归属)$/)).toHaveCount(3);
  await app.screenshot('workspace-task-desktop-context');
  await screen.getByRole('button', '收起上下文').click();

  const deferred = ['稍后甲：补充导航说明', '稍后乙：核对搜索入口', '稍后丙：这条应取消'];
  for (const text of deferred) {
    await taskChat.getByRole('combobox', '发送方式').selectOption({ value: 'defer' });
    await taskAComposer.fill(text);
    await taskChat.getByRole('button', '保存为稍后处理').click();
    await expect(taskAComposer).toHaveValue('');
  }
  await taskChat.getByText('稍后处理 3 条', { exact: true }).click();
  const queue = taskChat.getByRole('list', '稍后输入队列');
  await expect(queue.getByRole('listitem')).toHaveCount(3);
  await expect(queue.getByRole('listitem')).toContainText(deferred);
  expect((await workspace.inspect()).steers.filter(row => row.thread_id === taskA.thread_id)).toHaveLength(3);
  await taskAComposer.fill('尚未发送的新草稿');
  await queue.getByRole('listitem').filter({ hasText: deferred[0] }).getByRole('button', '编辑输入').click();
  const edited = '稍后甲：已修订的导航说明';
  await queue.getByLabel('编辑稍后输入').fill(edited);
  await queue.getByRole('button', '保存输入修改').click();
  await expect(queue.getByText(edited, { exact: true })).toBeVisible();
  await expect(taskAComposer).toHaveValue('尚未发送的新草稿');
  await queue.getByRole('listitem').filter({ hasText: deferred[1] }).getByRole('button', '上移').click();
  await expect(queue.getByRole('listitem')).toContainText([deferred[1], edited, deferred[2]]);
  await queue.getByRole('listitem').filter({ hasText: deferred[2] }).getByRole('button', '取消稍后输入').click();
  await expect(queue.getByRole('listitem')).toHaveCount(2);
  await expect(queue.getByRole('listitem')).toContainText([deferred[1], edited]);
  await queue.getByRole('listitem').filter({ hasText: deferred[1] }).getByRole('button', '现在处理').click();
  await expect(queue.getByRole('listitem')).toHaveCount(1);
  await queue.getByRole('listitem').filter({ hasText: edited }).getByRole('button', '现在处理').click();
  await expect(queue).toHaveCount(0);
  await expect.poll(async () => (await workspace.inspect()).steers.filter(row => row.thread_id === taskA.thread_id).length, { timeout: 30000 }).toBe(5);
  const released = (await workspace.inspect()).steers.filter(row => row.thread_id === taskA.thread_id);
  expect(new Set(released.map(row => row.message_id)).size).toBe(5);
  expect(released.slice(3).map(row => row.text.includes(deferred[1]) ? deferred[1] : row.text.includes(edited) ? edited : 'unexpected input')).toEqual([deferred[1], edited]);
  expect(released.some(row => row.text.includes(deferred[2]))).toBe(false);
  await taskAComposer.clear();
  await workspace.release('taskA');
  await expect.poll(async () => (await workspace.inspect()).turns.find(row => row.turn_id === taskATurn)?.state, { timeout: 30000 }).toBe('completed');
  await expect(taskChat).toContainText('workspace-task-a-only:complete', { timeout: 20000 });

  const taskBText = directive('workspace-task-b-only', workspace.gates.taskB);
  const taskBUrl = await createTask('检查独立搜索任务', taskBText);
  const taskB = await invocation('workspace-task-b-only');
  const taskBTurn = await turn(taskB.thread_id);
  expect(taskB.conversation_id).toBe(taskA.conversation_id);
  expect(new Set([main.thread_id, taskA.thread_id, taskB.thread_id]).size).toBe(3);
  expect(taskB.messages.some(message => /workspace-main-only|workspace-task-a-only|保留首页入口|已修订的导航说明/.test(message))).toBe(false);
  await expect(taskChat).toContainText('workspace-task-b-only');
  await expect(taskChat).not.toContainText('workspace-task-a-only');
  await expect(taskChat).not.toContainText('workspace-main-only');

  await browser.setViewport({ width: 390, height: 844 });
  await browser.reload();
  await expect(browser).toHaveURL(taskBUrl);
  const narrowComposer = taskChat.getByRole('textbox', '发给 Workspace Builder · 检查独立搜索任务');
  const narrowSend = taskChat.getByRole('button', '补充当前工作');
  const stop = taskChat.getByRole('button', '停止', { exact: true });
  await expect(narrowSend).toBeDisabled();
  await expect(stop).toBeEnabled();
  await narrowComposer.fill('手机中文补充');
  await browser.evaluate(() => {
    const field = document.getElementById('message-text');
    if (!(field instanceof HTMLTextAreaElement)) throw new Error('The visible composer must be a textarea');
    field.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true, data: '中文' }));
    field.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true, bubbles: true, cancelable: true }));
    return null;
  });
  await expect(narrowComposer).toHaveValue('手机中文补充');
  expect((await workspace.inspect()).steers.filter(row => row.thread_id === taskB.thread_id)).toEqual([]);
  await browser.evaluate(() => {
    document.getElementById('message-text')?.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true, data: '中文' }));
    return null;
  });
  await narrowComposer.press('Shift+Enter');
  await expect(narrowComposer).toHaveValue('手机中文补充\n');
  await narrowComposer.press('Tab');
  await expect(taskChat.getByRole('button', '添加附件', { exact: true })).toBeFocused();
  await narrowComposer.focus();
  await narrowComposer.press('Enter');
  await expect(narrowComposer).toHaveValue('');
  await expect(narrowComposer).toBeFocused();
  await expect.poll(async () => (await workspace.inspect()).steers.filter(row => row.thread_id === taskB.thread_id).map(row => ({ turn: row.turn_id, contains: row.text.includes('手机中文补充') })), { timeout: 30000 }).toEqual([{ turn: taskBTurn, contains: true }]);
  await narrowComposer.fill('停止后仍保留的草稿');
  await expect(narrowSend).toBeEnabled();
  await expect(stop).toBeEnabled();
  for (const control of [narrowComposer, narrowSend, stop]) {
    const bounds = await control.boundingBox();
    assert(bounds, 'The narrow composer controls render');
    expect(bounds.x).toBeGreaterThanOrEqual(0);
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(390);
  }
  expect(await browser.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await app.screenshot('workspace-task-narrow-input');
  await stop.click();
  await expect(narrowComposer).toHaveValue('停止后仍保留的草稿');
  await expect(narrowComposer).toBeFocused();
  await expect.poll(async () => (await workspace.inspect()).turns.find(row => row.turn_id === taskBTurn)?.state, { timeout: 30000 }).toBe('interrupted');
  const stopped = await workspace.inspect();
  expect(stopped.interrupts).toEqual([{ thread_id: taskB.thread_id, turn_id: taskBTurn }]);
  expect(stopped.turns.find(row => row.turn_id === mainTurn)?.state).toBe('inProgress');
  expect(stopped.turns.find(row => row.turn_id === taskATurn)?.state).toBe('completed');
  await browser.reload();
  await expect(browser).toHaveURL(taskBUrl);
  await expect(narrowComposer).toHaveValue('停止后仍保留的草稿');
  const restored = await workspace.inspect();
  expect(restored.invocations).toEqual(stopped.invocations);
  expect(restored.steers).toEqual(stopped.steers);
  expect(restored.interrupts).toEqual(stopped.interrupts);
  await browser.goto(taskAUrl);
  await expect(taskChat).toContainText(supplements[0]);
  await expect(taskChat).not.toContainText('workspace-task-b-only');
  await browser.goto(builderUrl);
  await expect(screen.getByRole('region', '对话')).toContainText('workspace-main-only');
  await expect(screen.getByRole('region', '对话')).not.toContainText('workspace-task-a-only');
  await expect(screen.getByRole('region', '对话')).not.toContainText('workspace-task-b-only');
  await workspace.release('main');
  await expect.poll(async () => (await workspace.inspect()).turns.find(row => row.turn_id === mainTurn)?.state, { timeout: 30000 }).toBe('completed');

  await browser.goto('/channels');
  await screen.getByRole('button', '新频道', { exact: true, visible: true }).first().click();
  const channelForm = screen.getByRole('dialog');
  await channelForm.getByLabel('频道名称', { exact: true }).fill('官网改版频道');
  await channelForm.getByLabel('频道目标', { exact: true }).fill('本人两个 Bot 协作检查官网');
  await channelForm.getByRole('checkbox', 'Workspace Builder').check();
  await channelForm.getByRole('checkbox', 'Workspace Reviewer').check();
  await channelForm.getByRole('combobox', '默认协调 Bot').selectOption({ label: 'Workspace Builder' });
  await channelForm.getByRole('button', '创建频道').click();
  await expect(browser).toHaveURL(/\/channels\/[^/?#]+$/);
  const channelUrl = await browser.url();
  await expect(screen.getByRole('heading', '官网改版频道', { level: 2 })).toBeVisible();
  const channelChat = screen.getByRole('region', '频道对话');
  await channelChat.getByRole('combobox', '频道消息目标').selectOption({ label: 'Workspace Reviewer' });
  const channelComposer = channelChat.getByRole('textbox', /^发给 Workspace Reviewer · /);
  await channelComposer.fill(directive('workspace-channel-directed', workspace.gates.channel));
  await channelChat.getByRole('button', '发送', { exact: true }).click();
  await expect(channelComposer).toHaveValue('');
  const directed = await invocation('workspace-channel-directed');
  const channelTurn = await turn(directed.thread_id);
  expect(directed.conversation_id).not.toBe(main.conversation_id);
  expect(directed.messages.some(message => /workspace-main-only|workspace-task-a-only|workspace-task-b-only/.test(message))).toBe(false);
  await workspace.release('channel');
  await expect.poll(async () => (await workspace.inspect()).turns.find(row => row.turn_id === channelTurn)?.state, { timeout: 30000 }).toBe('completed');
  await expect(channelChat).toContainText('workspace-channel-directed:complete', { timeout: 20000 });
  const taskLink = channelChat.getByRole('link').filter({ hasText: 'workspace-channel-directed' });
  await expect(taskLink).toHaveCount(1);
  const channelSend = channelChat.getByRole('button', /^(发送|补充当前工作)$/);
  for (const control of [channelComposer, channelSend]) {
    const bounds = await control.boundingBox();
    assert(bounds, 'The narrow Channel input and send button render');
    expect(bounds.x).toBeGreaterThanOrEqual(0);
    expect(bounds.y).toBeGreaterThanOrEqual(0);
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(390);
    expect(bounds.y + bounds.height).toBeLessThanOrEqual(844);
  }
  const channelLayout = await browser.evaluate(() => {
    const panel = document.querySelector('section[aria-label="频道对话"]');
    const form = panel?.querySelector(':scope > form');
    const history = panel?.querySelector('[aria-label="聊天记录"]');
    if (!(panel instanceof HTMLElement) || !(form instanceof HTMLFormElement) || !(history instanceof HTMLElement)) throw new Error('The Channel must render its composer and history viewport');
    const composer = form.getBoundingClientRect(), timeline = history.getBoundingClientRect();
    return { width: window.innerWidth, height: window.innerHeight, scrollWidth: document.documentElement.scrollWidth,
      panelHeight: panel.getBoundingClientRect().height, composerHeight: composer.height, composerTop: composer.top,
      historyHeight: timeline.height, historyBottom: timeline.bottom };
  });
  expect({ width: channelLayout.width, height: channelLayout.height }).toEqual({ width: 390, height: 844 });
  expect(channelLayout.scrollWidth).toBeLessThanOrEqual(channelLayout.width);
  expect(channelLayout.panelHeight).toBeGreaterThan(0);
  expect(channelLayout.composerHeight).toBeLessThanOrEqual(channelLayout.height / 2);
  expect(channelLayout.historyHeight).toBeGreaterThanOrEqual(channelLayout.panelHeight / 4);
  expect(channelLayout.historyBottom).toBeLessThanOrEqual(channelLayout.composerTop);
  await app.screenshot('workspace-channel-directed-narrow');
  await taskLink.click();
  await expect(browser).toHaveURL(/\/tasks\/[^/?#]+$/);
  await expect(taskChat.getByRole('textbox', /^发给 Workspace Reviewer · /)).toBeVisible();
  await expect(taskChat).toContainText('workspace-channel-directed:complete');
  await screen.getByRole('link', '打开频道', { exact: true }).click();
  await expect(browser).toHaveURL(channelUrl);
  await expect(channelChat).toContainText('workspace-channel-directed:complete');
  const finalEvidence = await workspace.inspect();
  expect(finalEvidence.starts.filter(row => row.thread_id === taskA.thread_id)).toHaveLength(1);
  expect(finalEvidence.steers.filter(row => row.thread_id === taskA.thread_id)).toHaveLength(5);
  expect(finalEvidence.steers.some(row => row.text.includes(deferred[2]))).toBe(false);
});
